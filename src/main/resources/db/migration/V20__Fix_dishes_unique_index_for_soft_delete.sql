-- Исправляем уникальный индекс для блюд, чтобы он учитывал только активные блюда
-- Это позволяет создавать новые блюда с тем же именем после удаления (soft delete) старых

-- Удаляем старый уникальный индекс
DROP INDEX IF EXISTS idx_dishes_name_restaurant;

-- Создаем частичный уникальный индекс только для активных блюд
-- Это позволяет иметь несколько неактивных блюд с одним именем,
-- но только одно активное блюдо с данным именем в ресторане
CREATE UNIQUE INDEX idx_dishes_name_restaurant_active 
ON dishes(name, restaurant_id) 
WHERE is_active = TRUE;




